# Generates client action modules (remoteAction wrappers) and the server registry.
import os, re, sys
root = sys.argv[1]
impl_dir = os.path.join(root, "src/server/actions-impl")
out_dir = os.path.join(root, "src/server/actions")
mods = []
for name in sorted(os.listdir(impl_dir)):
    if not name.endswith(".ts"): continue
    mod = name[:-3]
    code = open(os.path.join(impl_dir, name)).read()
    exports = re.findall(r'^export (?:const|async function) ([A-Za-z0-9_]+)', code, re.M)
    mods.append((mod, exports))
    lines = ['"use client";', "// Client entry points for the " + mod + " actions (generated by scripts/gen-actions.py).",
             "// Each call POSTs to /api/actions/" + mod + "/<name>; implementations live in src/server/actions-impl/" + mod + ".ts.",
             'import { remoteAction } from "@/lib/remote-action";', ""]
    for e in exports:
        lines.append(f'export const {e} = remoteAction("{mod}", "{e}");')
    open(os.path.join(out_dir, name), "w").write("\n".join(lines) + "\n")
reg = ['import "server-only";', "// Registry of callable actions (generated by scripts/gen-actions.py). Only modules listed here are reachable."]
for mod, _ in mods:
    reg.append(f'import * as {mod} from "@/server/actions-impl/{mod}";')
reg.append("")
reg.append("export const ACTION_MODULES: Record<string, Record<string, unknown>> = { " + ", ".join(m for m, _ in mods) + " };")
reg.append("")
reg.append("/** Actions callable without a session (sign-in, setup, invitations, password reset). */")
reg.append('export const PUBLIC_ACTIONS = new Set(["session.loginAction", "session.setupAction", "session.acceptInviteAction", "session.resetPasswordAction", "session.logoutAction"]);')
open(os.path.join(root, "src/server/action-registry.ts"), "w").write("\n".join(reg) + "\n")
print("modules:", len(mods), "actions:", sum(len(e) for _, e in mods))
